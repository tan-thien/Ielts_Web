export function translateText(value: string, language: AppLanguage): string {
    const leading = value.match(/^\s*/)?.[0] ?? "";
    const trailing = value.match(/\s*$/)?.[0] ?? "";
    const content = value.slice(leading.length, value.length - trailing.length);
    if (!content) return value;
    if (language === "en") {
        const range = content.match(/^Hiển thị (\d+)–(\d+) \/ (\d+)$/);
        if (range) return `${leading}Showing ${range[1]}–${range[2]} of ${range[3]}${trailing}`;
        const courseCount = content.match(/^(\d+) khóa học$/);
        if (courseCount) return `${leading}${courseCount[1]} courses${trailing}`;
    } else {
        const range = content.match(/^Showing (\d+)–(\d+) of (\d+)$/);
        if (range) return `${leading}Hiển thị ${range[1]}–${range[2]} / ${range[3]}${trailing}`;
        const courseCount = content.match(/^(\d+) courses$/);
        if (courseCount) return `${leading}${courseCount[1]} khóa học${trailing}`;
    }
    const dictionary = language === "en" ? vietnameseToEnglish : englishToVietnamese;
    const translated = dictionary[content];
    return translated ? `${leading}${translated}${trailing}` : value;
}
